// FormatYAML formats and validates YAML output
func FormatYAML(yamlContent string) (string, error) {
	var parsed interface{}
	err := yaml.Unmarshal([]byte(yamlContent), &parsed)
	if err != nil {
		return "", fmt.Errorf("invalid YAML: %w", err)
	}

	formatted, err := yaml.Marshal(parsed)
	if err != nil {
		return "", fmt.Errorf("failed to reformat YAML: %w", err)
	}

	return string(formatted), nil
}
